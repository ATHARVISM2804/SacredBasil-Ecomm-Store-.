// Generates supabase/seed.sql from data/catalog.ts. Run: node scripts/generate-seed.ts
import { writeFileSync } from "node:fs";
import { seedProducts } from "../data/catalog.ts";

const q = (v: unknown) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const j = (v: unknown) => (v === null || v === undefined ? "null" : `${q(JSON.stringify(v))}::jsonb`);
const arr = (v: string[]) => `array[${v.map(q).join(", ")}]::text[]`;

const rows = seedProducts.map(
  (p) =>
    `(${[q(p.id), q(p.slug), q(p.name), q(p.tagline), q(p.shortDescription), q(p.description), arr(p.images), j(p.contents), q(p.packaging), q(p.dimensions), j(p.variants), j(p.tiers), p.bespokeFrom ?? "null", q(p.customisation), p.stock ?? "null", q(p.status), p.featured, p.sortOrder].join(", ")})`,
);

const sql = `-- Generated by scripts/generate-seed.ts from data/catalog.ts. Do not edit by hand.
insert into public.products (id, slug, name, tagline, short_description, description, images, contents, packaging, dimensions, variants, tiers, bespoke_from, customisation, stock, status, featured, sort_order)
values
${rows.join(",\n")}
on conflict (id) do nothing;

insert into public.settings (key, value) values
  ('announcement', '{"text": "Planning festive or corporate gifts?", "link": "/corporate-gifting#enquire", "linkLabel": "Enquire for curated sets"}'::jsonb),
  ('shipping', '{"mode": "separate", "note": "Shipping is charged separately, based on destination and shipping option."}'::jsonb)
on conflict (key) do nothing;
`;
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log("wrote supabase/seed.sql with", rows.length, "products");
