"""Trace the master logo into the site's vector marks and the brandfix masks.

Usage: python make_brand.py

Source: docs/inputs/sb-monogram-hq.png (cream logo on maroon, 1254 px).
Writes:
  public/brand/sb-{monogram,wordmark,lockup}.svg   currentColor vectors
  components/ui/logo-paths.ts                     paths for <Logo>
  scripts/brandfix/masks/sb-*.png                 alpha masks for brandfix.py
Each crop keeps a margin around the ink so no stroke can be clipped, and the
trace is checked against the source (IoU) before anything is written.
"""
import re
import subprocess
import tempfile
from pathlib import Path

import cv2
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "docs/inputs/sb-monogram-hq.png"
UP = 4      # trace at 4x the source resolution
PAD = 4     # source px of margin around the ink


def bands(ink):
    rows = np.nonzero(ink.any(1))[0]
    cut = np.nonzero(np.diff(rows) > 5)[0][0]
    return (rows[0], rows[cut]), (rows[cut + 1], rows[-1])


def box(ink, y0, y1):
    cols = np.nonzero(ink[y0:y1 + 1].any(0))[0]
    return cols[0] - PAD, y0 - PAD, cols[-1] + PAD + 1, y1 + PAD + 1


def trace(L, mid, b, tmp, name):
    x0, y0, x1, y1 = b
    c = cv2.resize(L[y0:y1, x0:x1], None, fx=UP, fy=UP, interpolation=cv2.INTER_CUBIC)
    c = cv2.GaussianBlur(c, (0, 0), 1.2)
    pbm = tmp / f"{name}.pbm"
    cv2.imwrite(str(pbm), (c < mid).astype(np.uint8) * 255)  # OpenCV PBM: 0 = black = traced
    svg = tmp / f"{name}.svg"
    subprocess.run(["potrace", str(pbm), "-s", "-t", "4", "-a", "1.0", "-O", "0.2", "-o", str(svg)], check=True)
    text = svg.read_text()
    w, h = re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', text).groups()
    transform = re.search(r'<g transform="([^"]+)"', text).group(1)
    d = " ".join(" ".join(p.split()) for p in re.findall(r'<path d="([^"]+)"', text, re.S))
    return {"viewBox": f"0 0 {int(float(w))} {int(float(h))}", "transform": transform, "d": d}


def svg_text(m):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{m["viewBox"]}" role="img" aria-label="Sacred Basil">'
            f'<g transform="{m["transform"]}" fill="currentColor" stroke="none"><path d="{m["d"]}"/></g></svg>\n')


def render(svg_path, width):
    """Rasterise with sharp (as the site's browsers would) to an alpha mask."""
    out = svg_path.with_suffix(".png")
    js = (f"require('sharp')(process.argv[1],{{density:300}}).resize({{width:{width}}})"
          ".ensureAlpha().png().toFile(process.argv[2])")
    subprocess.run(["node", "-e", js, str(svg_path), str(out)], check=True, cwd=ROOT)
    return out


def main():
    img = cv2.imread(str(SRC))
    L = cv2.cvtColor(img, cv2.COLOR_BGR2LAB)[:, :, 0].astype(np.float32)
    bg, fg = np.percentile(L, 1), np.percentile(L, 99)
    mid = (bg + fg) / 2
    ink = L > mid
    (m0, m1), (w0, w1) = bands(ink)
    boxes = {"monogram": box(ink, m0, m1), "wordmark": box(ink, w0, w1)}
    mono, word = boxes["monogram"], boxes["wordmark"]
    boxes["lockup"] = (min(mono[0], word[0]), mono[1], max(mono[2], word[2]), word[3])

    tmp = Path(tempfile.mkdtemp())
    marks = {}
    for name, b in boxes.items():
        m = trace(L, mid, b, tmp, name)
        f = tmp / f"{name}-check.svg"
        f.write_text(svg_text(m).replace("currentColor", "#000"))
        x0, y0, x1, y1 = b
        r = cv2.imread(str(render(f, (x1 - x0) * UP)), cv2.IMREAD_UNCHANGED)[:, :, 3]
        r = cv2.resize(r, (x1 - x0, y1 - y0), interpolation=cv2.INTER_AREA) > 127
        src = ink[y0:y1, x0:x1]
        iou = (r & src).sum() / (r | src).sum()
        edge = r[0].any() or r[-1].any() or r[:, 0].any() or r[:, -1].any()
        print(f"{name}: box {b}, IoU {iou:.4f}, touches edge {edge}")
        assert iou > (0.95 if name == "wordmark" else 0.99) and not edge, name
        marks[name] = m

    for name, m in marks.items():
        (ROOT / f"public/brand/sb-{name}.svg").write_text(svg_text(m))
        black = tmp / f"{name}-mask.svg"
        black.write_text(svg_text(m).replace("currentColor", "#000"))
        mask = render(black, 2400)
        (ROOT / f"scripts/brandfix/masks/sb-{name}.png").write_bytes(mask.read_bytes())

    ts = ["/* Generated by scripts/brandfix/make_brand.py from docs/inputs/sb-monogram-hq.png. Do not edit by hand. */", ""]
    for name in ("monogram", "wordmark"):
        m = marks[name]
        ts.append(f'export const {name} = {{ viewBox: "{m["viewBox"]}", transform: "{m["transform"]}", d: "{m["d"]}" }};')
    (ROOT / "components/ui/logo-paths.ts").write_text("\n".join(ts) + "\n")


if __name__ == "__main__":
    main()
